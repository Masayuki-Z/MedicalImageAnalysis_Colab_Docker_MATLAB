function validateTransform(transformMatrix)
%VALIDATETRANSFORM Validate a finite invertible homogeneous 2-D transform.
if ~isnumeric(transformMatrix) || ~isequal(size(transformMatrix), [3 3]) || ...
        any(~isfinite(transformMatrix(:))) || ...
        abs(det(transformMatrix)) < eps || ...
        any(abs(transformMatrix(3, :) - [0 0 1]) > 1e-12)
    error("MedicalImageToolbox:TransformMatrix", ...
        "Transform must be an invertible 3-by-3 affine matrix with last row [0 0 1].");
end
end
