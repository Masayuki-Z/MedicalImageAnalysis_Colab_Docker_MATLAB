function validateColorBounds(lowerBounds, upperBounds, space, allowHueWrap)
%VALIDATECOLORBOUNDS Validate three normalized channel bounds.
if nargin < 4
    allowHueWrap = false;
end
if ~isnumeric(lowerBounds) || ~isnumeric(upperBounds) || ...
        numel(lowerBounds) ~= 3 || numel(upperBounds) ~= 3 || ...
        any(~isfinite(lowerBounds(:))) || any(~isfinite(upperBounds(:))) || ...
        any(lowerBounds(:) < 0 | lowerBounds(:) > 1) || ...
        any(upperBounds(:) < 0 | upperBounds(:) > 1)
    error("MedicalImageToolbox:ColorBounds", ...
        "%s lower/upper bounds must be three-element vectors in [0, 1].", space);
end
if ~allowHueWrap && any(lowerBounds(:) > upperBounds(:))
    error("MedicalImageToolbox:ColorBoundsOrder", ...
        "%s lower bounds must not exceed upper bounds.", space);
end
if allowHueWrap && any(lowerBounds(2:3) > upperBounds(2:3))
    error("MedicalImageToolbox:ColorBoundsOrder", ...
        "HSV saturation and value lower bounds must not exceed their upper bounds.");
end
end
