function state = initializeImageState(originalImage)
%INITIALIZEIMAGESTATE Create independent processing states around an immutable source.
validateImage(originalImage);
state = struct( ...
    "OriginalImage", originalImage, ...
    "EnhancedImage", [], ...
    "TransformedImage", [], ...
    "ClassicalSegmentationMask", [], ...
    "AISegmentationInput", [], ...
    "AIProbabilityMap", [], ...
    "AIPredictedMask", [], ...
    "GroundTruthMask", [], ...
    "CurrentInputName", "original", ...
    "CurrentInput", originalImage, ...
    "ProcessingHistory", struct("Operation", {}, "InputState", {}, ...
        "OutputState", {}, "Parameters", {}));
end
