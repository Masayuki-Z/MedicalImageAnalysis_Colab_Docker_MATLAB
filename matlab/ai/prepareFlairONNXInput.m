function [modelImage, metadata] = prepareFlairONNXInput(image)
%PREPAREFLAIRONNXINPUT Prepare one MRI FLAIR plane exactly as the PyTorch loader.
validateImage(image);
if ndims(image) == 3
    flairPlane = image(:, :, 2);
else
    flairPlane = image;
end

if isa(flairPlane, "uint8")
    pythonPlane = flairPlane;
elseif isfloat(flairPlane)
    if any(~isfinite(flairPlane(:))) || any(flairPlane(:) < 0 | flairPlane(:) > 1)
        error("MedicalImageToolbox:FLAIRRange", ...
            "Floating-point FLAIR values must be finite and in [0, 1].");
    end
    pythonPlane = single(flairPlane);
elseif islogical(flairPlane)
    pythonPlane = single(flairPlane);
else
    error("MedicalImageToolbox:FLAIRDataType", ...
        "ONNX preprocessing accepts uint8 MRI or floating-point FLAIR in [0, 1].");
end

bridge = getGliomaONNXBridge();
try
    prepared = cell(bridge.preprocess_flair_plane( ...
        py.numpy.asarray(pythonPlane)));
catch exception
    error("MedicalImageToolbox:FLAIRPreprocessing", ...
        "Python preprocessing failed: %s", exception.message);
end
if numel(prepared) ~= 4
    error("MedicalImageToolbox:FLAIRPreprocessing", ...
        "Python preprocessing returned an unexpected result.");
end
inputNCHW = single(prepared{1});
if ~isequal(size(inputNCHW), [1 1 256 256]) || ...
        any(~isfinite(inputNCHW(:)))
    error("MedicalImageToolbox:FLAIRPreprocessing", ...
        "Preprocessed input must be finite float32 with shape [1 1 256 256].");
end
modelImage = reshape(inputNCHW, [256 256]);
metadata = struct( ...
    "SourceChannel", "RGB channel 2 (MATLAB indexing); grayscale is selected FLAIR", ...
    "ChannelIndexZeroBased", 1, ...
    "InputSize", [256 256], ...
    "OriginalSize", double(prepared{4}), ...
    "DataType", "single", ...
    "InputShapeNCHW", [1 1 256 256], ...
    "Normalization", "per-slice population z-score after float32 scale to [0,1]", ...
    "NormalizationMean", double(prepared{2}), ...
    "NormalizationStandardDeviation", double(prepared{3}), ...
    "Epsilon", 1e-6, ...
    "ResizeInterpolation", "Pillow bilinear; resize only when needed");
end