function [state, probabilityMap, predictionMask, modelMetadata] = runGliomaONNX(state, modelPath)
%RUNGLIOMAONNX Run the preserved U-Net ONNX model through ONNX Runtime Python.
if nargin < 2 || ~(ischar(modelPath) || (isstring(modelPath) && isscalar(modelPath))) || ...
        strlength(string(modelPath)) == 0
    error("MedicalImageToolbox:ONNXModelPath", ...
        "Provide the path to the trained ONNX model.");
end
modelPath = char(modelPath);
if ~isfile(modelPath)
    error("MedicalImageToolbox:ONNXModelMissing", ...
        "ONNX model file does not exist: %s", modelPath);
end
validateImageStateForONNX(state);

[modelImage, preprocessing] = prepareFlairONNXInput(state.OriginalImage);
bridge = getGliomaONNXBridge();
try
    modelMetadata = jsondecode(char( ...
        bridge.get_model_metadata_json(modelPath)));
    modelInput = reshape(modelImage, [1 1 256 256]);
    pythonOutput = bridge.run_onnx_inference( ...
        modelPath, py.numpy.asarray(modelInput));
    probabilities = single(pythonOutput);
catch exception
    error("MedicalImageToolbox:ONNXInference", ...
        "ONNX Runtime inference failed: %s", exception.message);
end
if ~isequal(size(probabilities), [1 1 256 256])
    error("MedicalImageToolbox:ONNXOutputDimensions", ...
        "ONNX output must be float32 [1 1 256 256].");
end
probabilityMap = reshape(probabilities, [256 256]);
if any(~isfinite(probabilityMap(:))) || ...
        any(probabilityMap(:) < 0 | probabilityMap(:) > 1)
    error("MedicalImageToolbox:ONNXProbabilityRange", ...
        "ONNX output probabilities must be finite and in [0, 1].");
end
[probabilityMap, predictionMask] = restoreGliomaPrediction( ...
    probabilityMap, size(state.OriginalImage, 1:2), 0.5);

metadata = struct( ...
    "Backend", "Python ONNX Runtime via MATLAB Python interface", ...
    "ModelPath", string(modelPath), ...
    "ONNXInputName", string(modelMetadata.input_name), ...
    "ONNXOutputName", string(modelMetadata.output_name), ...
    "ONNXInputShape", [1 1 256 256], ...
    "ONNXOutputShape", [1 1 256 256], ...
    "ONNXRuntimeVersion", string(modelMetadata.onnxruntime_version), ...
    "ExecutionProviders", string(modelMetadata.providers), ...
    "Architecture", "original_2d_unet", ...
    "Threshold", 0.5, ...
    "Preprocessing", preprocessing);
state = recordImageResult(state, "aiInput", modelImage, ...
    "prepareFlairONNXInput", preprocessing, "original");
state = recordImageResult(state, "aiProbabilityMap", ...
    reshape(probabilities, [256 256]), "runGliomaONNX", metadata, "aiInput");
state = recordImageResult(state, "aiPredictedMask", predictionMask, ...
    "thresholdAndRestorePrediction", metadata, "aiInput");
end

function validateImageStateForONNX(state)
required = ["OriginalImage", "EnhancedImage", "TransformedImage", ...
    "ClassicalSegmentationMask", "AISegmentationInput", "AIProbabilityMap", ...
    "AIPredictedMask", "GroundTruthMask", ...
    "CurrentInputName", "CurrentInput", "ProcessingHistory"];
if ~isstruct(state) || ~isscalar(state) || ~all(isfield(state, required))
    error("MedicalImageToolbox:InvalidImageState", ...
        "State must be created by initializeImageState.");
end
validateImage(state.OriginalImage);
end